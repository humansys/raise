class _SectionSpec(NamedTuple):
    """Conditional section check — only runs if section_key is present in yaml data."""

    section_key: str
    required_keys: tuple[str, ...]
    optional_keys: tuple[str, ...]


class _AdapterSpec(NamedTuple):
    """Schema specification for a known adapter config file."""

    required_keys: tuple[str, ...]
    optional_keys: tuple[str, ...]
    sections: tuple[_SectionSpec, ...] = ()


# Known adapter filenames → schema.  Extend this map to add new adapters.
# For backlog.yaml the required/optional checks are conditional on the
# presence of the "jira" section — encoded via _SectionSpec.
_ADAPTER_SCHEMAS: dict[str, _AdapterSpec] = {
    "jira.yaml": _AdapterSpec(
        required_keys=("default_instance",),
        optional_keys=("instances", "projects"),
    ),
    # confluence.yaml is legacy (canonical is docs.yaml); schema varies by
    # format version (flat url vs multi-instance). Omitted until a stable
    # schema can be derived from ConfluenceConfig/ConfluenceInstanceConfig.
    "backlog.yaml": _AdapterSpec(
        required_keys=(),
        optional_keys=(),
        sections=(
            _SectionSpec(
                section_key="jira",
                required_keys=("default_org",),
                optional_keys=("organizations",),
            ),
        ),
    ),
}


def _adapter_key_findings(
    data: dict[str, object],
    required_keys: tuple[str, ...],
    optional_keys: tuple[str, ...],
    filename: str,
    config_path: Path,
    key_prefix: str = "",
) -> list[WorkspaceReadinessFinding]:
    """Return findings for missing required/optional keys in `data`.

    key_prefix is prepended to key names in messages and evidence when checking
    conditional section keys (e.g. "jira." for backlog.yaml's jira section).
    """
    findings: list[WorkspaceReadinessFinding] = []
    for key in required_keys:
        if key not in data:
            full = f"{key_prefix}{key}"
            findings.append(
                WorkspaceReadinessFinding(
                    code="adapter_config_missing_required_key",
                    message=f"{filename}: required key '{full}' is missing",
                    severity="required",
                    path=config_path,
                    evidence={"adapter": filename, "key": full},
                )
            )
    for key in optional_keys:
        if key not in data:
            full = f"{key_prefix}{key}"
            findings.append(
                WorkspaceReadinessFinding(
                    code="adapter_config_missing_optional_key",
                    message=f"{filename}: optional key '{full}' is missing",
                    severity="advisory",
                    path=config_path,
                    evidence={"adapter": filename, "key": full},
                )
            )
    return findings


def _adapter_file_findings(
    filename: str, spec: _AdapterSpec, config_path: Path
) -> list[WorkspaceReadinessFinding]:
    """Return all findings for one adapter config file.

    Handles parse errors, top-level key checks, and conditional section checks.
    """
    try:
        raw: object = yaml.safe_load(config_path.read_text(encoding="utf-8"))
    except (yaml.YAMLError, OSError) as exc:
        return [
            WorkspaceReadinessFinding(
                code="adapter_config_parse_error",
                message=f"{filename} is not valid YAML: {exc}",
                severity="required",
                path=config_path,
                evidence={"error": str(exc)},
            )
        ]

    # yaml.safe_load returns None for an empty or comment-only file —
    # treat that as an empty document (no keys to validate).
    if raw is None:
        raw = {}

    if not isinstance(raw, dict):
        return [
            WorkspaceReadinessFinding(
                code="adapter_config_parse_error",
                message=f"{filename} must be a YAML mapping, got {type(raw).__name__}",
                severity="required",
                path=config_path,
            )
        ]

    data: dict[str, object] = raw
    findings = _adapter_key_findings(
        data, spec.required_keys, spec.optional_keys, filename, config_path
    )
    for section_spec in spec.sections:
        section = data.get(section_spec.section_key)
        if section is None or not isinstance(section, dict):
            continue  # section absent — not a finding
        findings.extend(
            _adapter_key_findings(
                section,
                section_spec.required_keys,
                section_spec.optional_keys,
                filename,
                config_path,
                key_prefix=f"{section_spec.section_key}.",
            )
        )
    return findings


def _check_adapter_config(path: Path) -> list[WorkspaceReadinessFinding]:
    """Advisory/required: validate adapter config files found in .raise/.

    Scans path/.raise/ for known adapter yaml files (jira.yaml, confluence.yaml,
    backlog.yaml).  For each found file:
      - YAML parse error        → severity="required", code="adapter_config_parse_error"
      - Missing required key    → severity="required", code="adapter_config_missing_required_key"
      - Missing optional key    → severity="advisory", code="adapter_config_missing_optional_key"

    Absence of an adapter file is not a finding — the adapter may not be
    configured for this project.  No network calls; filesystem-only.
    """
    raise_dir = path / ".raise"
    if not raise_dir.is_dir():
        return []
    findings: list[WorkspaceReadinessFinding] = []
    for filename, spec in _ADAPTER_SCHEMAS.items():
        config_path = raise_dir / filename
        if config_path.exists():
            findings.extend(_adapter_file_findings(filename, spec, config_path))
    return findings


def _check_tracked_runtime_configs(
    path: Path,
) -> list[WorkspaceReadinessFinding]:
    """Require checkout-specific runtime configs to be untracked local state."""
    findings: list[WorkspaceReadinessFinding] = []
    for relative_path in _RUNTIME_CONFIG_PATHS:
        if _is_git_tracked(path, relative_path):
            config_path = path / relative_path
            findings.append(
                WorkspaceReadinessFinding(
                    code="tracked_runtime_config",
                    message=(
                        f"{relative_path} is tracked branch content and was preserved. "
                        "Migrate it with a governed untrack-and-ignore commit before "
                        "re-provisioning."
                    ),
                    severity="required",
                    path=config_path,
                    evidence={"path": relative_path},
                )
            )
    return findings


def git_worktree_readiness_policy() -> WorkspaceReadinessPolicy:
    """Return the standard readiness policy for a git worktree provisioned by RaiSE.

    Checks (all required unless noted):
    - workspace root exists and is a directory
    - .codex/config.toml exists and contains mcp_servers shape
    - .mcp.json exists and is a valid JSON object
    - .hermes/config.yaml exists and is non-empty
    - .venv/bin/python exists as a file (not just a directory)
    - .venv-mcp/bin/python exists as a file
    - generated skills are not drifted
    - runtime command entries are not bare or outside the workspace
    - adapter config files in .raise/ have required keys (advisory: optional keys)

    Returns:
        A WorkspaceReadinessPolicy with all standard git worktree checks.
    """
    return WorkspaceReadinessPolicy(
        policy_id="git-worktree-v1",
        checks=[
            _check_workspace_root,
            _check_codex_config,
            _check_mcp_json,
            _check_hermes_config,
            _check_venv_python,
            _check_venv_mcp_python,
            _check_skill_drift,
            _check_runtime_commands,
            _check_tracked_runtime_configs,
            _check_adapter_config,
        ],
    )


def validate_provision(worktree_path: Path) -> list[str]:
    """Validate that critical files exist after provisioning.

    Backwards-compatible V1 API. Delegates to the structured readiness evaluator
    and returns required finding messages as plain strings for existing callers.

    For structured access, use:
        evaluate_workspace_readiness(worktree_path, git_worktree_readiness_policy())
    """
    report = evaluate_workspace_readiness(
        worktree_path, git_worktree_readiness_policy()
    )
    return [f.message for f in report.required_findings]


def _is_git_tracked(repo_root: Path, entry: str) -> bool:
    """Return True if `entry` (file or directory) has any git-tracked paths.

    Versioned entries already arrive correctly in a worktree via
    `git worktree add <branch>` — they match the worktree's OWN branch, not
    whatever `repo_root` happens to be parked on. Propagating them from
    `repo_root` (which may be a stale main checkout) would silently
    overwrite/symlink the worktree's own branch content (RAISE-13321).

    Returns False (not tracked) if `repo_root` is not a git repository —
    this keeps propagation working against plain non-repo fixture directories.
    """
    if not (repo_root / ".git").exists():
        return False
    try:
        result = subprocess.run(
            ["git", "ls-files", "--", entry],
            cwd=str(repo_root),
            capture_output=True,
            text=True,
            timeout=10,
        )
    except (OSError, subprocess.TimeoutExpired):
        return False
    return result.returncode == 0 and bool(result.stdout.strip())


def _git_porcelain_entries(repo_root: Path) -> dict[str, str]:
    """Return Git-visible worktree entries keyed by path."""
    if not (repo_root / ".git").exists():
        return {}
    try:
        result = subprocess.run(
            ["git", "status", "--porcelain=v1", "--untracked-files=all"],
            cwd=str(repo_root),
            capture_output=True,
            text=True,
            timeout=10,
        )
    except (OSError, subprocess.TimeoutExpired):
        return {}
    if result.returncode != 0:
        return {}
    return {line[3:]: line for line in result.stdout.splitlines() if len(line) >= 4}


def propagate_worktreeinclude(src_root: Path, dst_path: Path) -> tuple[int, list[str]]:
    """Propagate files listed in .worktreeinclude from src_root into dst_path.

    Files are copied; directories are symlinked. Missing entries produce
    warnings but do not fail. Idempotent: existing symlinks are skipped.
    Git-tracked (versioned) entries are always skipped — they belong to the
    destination worktree's own branch checkout, never to src_root (RAISE-13321).

    Returns (files_propagated, warnings).
    """
    wti = src_root / ".worktreeinclude"
    if not wti.exists():
        return 0, [f".worktreeinclude not found in {src_root}"]

    count = 0
    warnings: list[str] = []

    for raw in wti.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        entry = line.rstrip("/")
        if entry in _LOCAL_VENV_DIRS:
            # Never symlink a shared venv — it is created locally per worktree (C4).
            _log.debug(
                "Skipping %s in propagation — created locally per worktree", entry
            )
            continue
        if entry in _RUNTIME_CONFIG_PATHS:
            warnings.append(
                f"{entry} is a worktree-local runtime config and was not propagated"
            )
            continue
        if _is_git_tracked(src_root, entry):
            # Versioned — already arrives correctly from the worktree's own
            # branch checkout. Propagating from src_root would source it from
            # a possibly-stale main instead (RAISE-13321).
            _log.debug(
                "Skipping %s in propagation — git-tracked, sourced from branch checkout",
                entry,
            )
            continue
        src = src_root / entry
        if not src.exists():
            warnings.append(
                f"{entry} listed in .worktreeinclude but not found in {src_root}"
            )
            continue

        dst = dst_path / entry
        if src.is_dir():
            if not dst.exists():
                dst.symlink_to(src.resolve())
                count += 1
        else:
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src, dst)
            count += 1

    return count, warnings


class WorktreeProvisioner:
    """Orchestrates worktree provisioning: propagate + generate + validate."""

    def __init__(self, worktree_path: Path, repo_root: Path) -> None:
        self._wt = worktree_path
        self._repo = repo_root

    def _propagate_worktreeinclude(self) -> tuple[int, list[str]]:
        """Propagate files from .worktreeinclude. Returns (count, warnings).

        Delegates to the module-level `propagate_worktreeinclude()` so this
        call path and the CLI's direct call path (cli/commands/worktree.py)
        share one implementation — a prior duplicated copy of this logic here
        silently drifted from the module-level fix for git-tracked entries
        (RAISE-13321).
        """
        return propagate_worktreeinclude(self._repo, self._wt)

    def _create_mcp_venv(self) -> tuple[bool, list[str]]:
        """Create isolated .venv-mcp for the MCP server via uv sync.

        Skipped for non-Python projects (no pyproject.toml / uv.toml) — the MCP
        server is resolved from the global rai installation in those cases (RAISE-15153).
        """
        if not _has_python_project(self._wt):
            return True, []

        mcp_venv = self._wt / ".venv-mcp"
        if mcp_venv.is_dir():
            return True, []

        env = {**os.environ, "UV_PROJECT_ENVIRONMENT": str(mcp_venv)}
        try:
            subprocess.run(
                ["uv", "sync", "--frozen"],
                cwd=str(self._wt),
                env=env,
                capture_output=True,
                check=True,
                timeout=120,
            )
        except (subprocess.CalledProcessError, FileNotFoundError, TimeoutError) as exc:
            return False, [f".venv-mcp creation failed: {exc}"]
        return True, []

    def _create_main_venv(self) -> tuple[bool, list[str]]:
        """Create a worktree-local .venv via uv sync (E10436 S1, fixes C4).

        A real local .venv makes the editable .pth resolve raise_cli to THIS
        worktree's src, so in-worktree gates run the worktree's code. A
        pre-existing real .venv is left untouched (idempotent); a stale shared
        .venv symlink is removed and replaced by a real local venv.

        Skipped for non-Python projects (no pyproject.toml / uv.toml) — those
        have no Python dependencies and do not need a local venv (RAISE-15153).
        """
        if not _has_python_project(self._wt):
            return True, []

        venv = self._wt / ".venv"
        if venv.is_symlink():
            # Stale shared-venv pointer (the C4 case) — drop it, then sync locally.
            venv.unlink()
        elif venv.is_dir():
            return True, []

        env = {**os.environ, "UV_PROJECT_ENVIRONMENT": str(venv)}
        try:
            subprocess.run(
                ["uv", "sync"],
                cwd=str(self._wt),
                env=env,
                capture_output=True,
                check=True,
                timeout=300,
            )
        except (subprocess.CalledProcessError, FileNotFoundError, TimeoutError) as exc:
            return False, [f".venv creation failed: {exc}"]
        return True, []

    def _write_hermes_config(self) -> bool:
        """Write .hermes/config.yaml with structured upsert (preserves user entries)."""
        if _is_git_tracked(self._wt, ".hermes/config.yaml"):
            return False
        content = _render_hermes_config_content(self._wt)
        config_path = self._wt / ".hermes" / "config.yaml"
        return _write_config_if_changed(config_path, content)

    def _write_mcp_json(self) -> bool:
        """Write .mcp.json with structured upsert (preserves user entries)."""
        if _is_git_tracked(self._wt, ".mcp.json"):
            return False
        content = _render_mcp_json_content(self._wt)
        return _write_config_if_changed(self._wt / ".mcp.json", content)

    def _write_codex_config(self) -> bool:
        """Write .codex/config.toml with rai-workspace MCP server entry.

        Uses render_codex_config_toml from the builder module (S15457.3 AC1):
        - No hand-composed literals; output matches codex_plugin.post_init (AC4).
        - Absolute --project path resolves worktree_mismatch errors (AC2).
        - enabled_tools and env.RAISE_PROJECT_ROOT are never omitted (AC4/AC5).
        """
        if _is_git_tracked(self._wt, ".codex/config.toml"):
            return False
        content = _render_codex_config_content(self._wt)
        return _write_config_if_changed(self._wt / ".codex" / "config.toml", content)

    def _sync_skills(self) -> int:
        """Sync .claude/skills/ → skills_base/ + agent mirror dirs (RAISE-11153).

        Closes the gap where a freshly provisioned worktree fails the
        check-skills-sync pre-commit hook on first commit.
        """
        result = _build_skill_syncer(self._wt).sync()
        return len(result.synced_to_skills_base)

    def provision(self, *, dry_run: bool = False) -> ProvisionResult:
        """Run provisioning: propagate files, generate config, validate."""
        if dry_run:
            gen = HermesConfigGenerator(worktree_path=self._wt)
            config = gen.generate()
            _log.info(
                "[dry-run] Would write .hermes/config.yaml:\n%s", config.to_yaml()
            )
            return ProvisionResult(dry_run=True)

        before_drift = _git_porcelain_entries(self._wt)
        main_venv_created, main_warnings = self._create_main_venv()
        mcp_venv_created, mcp_warnings = self._create_mcp_venv()
        # .venv-mcp must exist before writing .mcp.json and .codex/config.toml
        # so the absolute rai-mcp-pipeline path can be resolved (RAISE-10767).
        mcp_json_written = self._write_mcp_json()
        codex_config_written = self._write_codex_config()
        _log.debug("codex_config_written=%s", codex_config_written)
        propagated, prop_warnings = self._propagate_worktreeinclude()
        hermes_written = self._write_hermes_config()
        # Skill projections are branch-owned source. Updating them remains an
        # explicit governed ``rai skill sync`` operation.
        skills_synced = 0

        report = evaluate_workspace_readiness(self._wt, git_worktree_readiness_policy())
        after_drift = _git_porcelain_entries(self._wt)
        introduced_drift = [
            entry
            for path, entry in after_drift.items()
            if path not in before_drift and path not in _LOCK_FILE_NAMES
        ]
        if introduced_drift:
            report = report.model_copy(
                update={
                    "findings": [
                        *report.findings,
                        WorkspaceReadinessFinding(
                            code="provision_introduced_git_drift",
                            message=(
                                "Provisioning introduced Git-visible drift: "
                                + ", ".join(introduced_drift)
                            ),
                            severity="required",
                            evidence={"entries": introduced_drift},
                        ),
                    ]
                }
            )
        readiness_warnings = [f.message for f in report.required_findings]

        return ProvisionResult(
            hermes_config_written=hermes_written,
            mcp_json_written=mcp_json_written,
            mcp_venv_created=mcp_venv_created,
            main_venv_created=main_venv_created,
            files_propagated=propagated,
            skills_synced=skills_synced,
            warnings=main_warnings + mcp_warnings + prop_warnings + readiness_warnings,
            introduced_drift=introduced_drift,
            readiness_report=report,
            is_ready=report.is_ready,
        )


