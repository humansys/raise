ApplyStatus = Literal["written", "unchanged", "git-tracked", "not-main-checkout"]


class ConfigApplyResult(BaseModel, frozen=True):
    """Structured result of ``apply_runtime_config``."""

    status: ApplyStatus
    was_tracked: bool = False


def _write_config_if_changed(path: Path, content: str) -> bool:
    """Write *content* to *path* only when different from current text.

    Creates parent directories if needed.  Returns True when the file was
    actually written; False when content was identical (mtime untouched).
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists():
        try:
            existing = path.read_text(encoding="utf-8")
        except OSError:
            existing = None
        if existing == content:
            return False
    atomic_write(path, content)
    return True


def _render_mcp_json_content(wt: Path) -> str:
    """Generate .mcp.json content with upsert merge (preserves user entries)."""
    gen = McpJsonGenerator(worktree_path=wt)
    config = gen.generate()

    mcp_json_path = wt / ".mcp.json"
    existing_data: dict[str, object] = {}
    if mcp_json_path.exists():
        try:
            parsed: object = json.loads(mcp_json_path.read_text(encoding="utf-8"))
            if isinstance(parsed, dict):
                existing_data = parsed
            else:
                _log.warning(
                    ".mcp.json is not a JSON object — overwriting with fresh content"
                )
        except (json.JSONDecodeError, OSError) as exc:
            _log.warning(
                ".mcp.json is malformed (%s) — overwriting with fresh content", exc
            )

    mcp_servers_raw = existing_data.get("mcpServers", {})
    if not isinstance(mcp_servers_raw, dict):
        mcp_servers_raw = {}
    mcp_servers: dict[str, object] = dict(mcp_servers_raw)

    new_json_data: dict[str, object] = json.loads(config.to_json())
    new_servers = new_json_data.get("mcpServers", {})
    if isinstance(new_servers, dict):
        mcp_servers.update(new_servers)

    result_data: dict[str, object] = dict(existing_data)
    result_data["mcpServers"] = mcp_servers
    return json.dumps(result_data, indent=2) + "\n"


def _render_hermes_config_content(wt: Path) -> str:
    """Generate .hermes/config.yaml content with upsert merge (preserves user entries)."""
    gen = HermesConfigGenerator(worktree_path=wt)
    config = gen.generate()

    config_path = wt / ".hermes" / "config.yaml"
    existing_data: dict[str, object] = {}
    if config_path.exists():
        try:
            parsed_yaml = yaml.safe_load(config_path.read_text(encoding="utf-8"))
            if isinstance(parsed_yaml, dict):
                existing_data = parsed_yaml
            else:
                _log.warning(".hermes/config.yaml is not a YAML mapping — overwriting")
        except Exception as exc:  # noqa: BLE001
            _log.warning(".hermes/config.yaml is malformed (%s) — overwriting", exc)

    mcp_servers_raw = existing_data.get("mcp_servers", {})
    if not isinstance(mcp_servers_raw, dict):
        mcp_servers_raw = {}
    mcp_servers: dict[str, object] = dict(mcp_servers_raw)

    new_yaml_data = yaml.safe_load(config.to_yaml())
    if isinstance(new_yaml_data, dict):
        new_servers = new_yaml_data.get("mcp_servers", {})
        if isinstance(new_servers, dict):
            mcp_servers.update(new_servers)

    result_data: dict[str, object] = dict(existing_data)
    result_data["mcp_servers"] = mcp_servers
    return yaml.dump(result_data, default_flow_style=False, sort_keys=False)


def _render_codex_config_content(wt: Path) -> str:
    """Generate .codex/config.toml content."""
    mcp_command = detect_mcp_pipeline_command(wt)
    return render_codex_config_toml(command=mcp_command, project_root=wt)


_RenderFn = Callable[[Path], str]

_RENDER_DISPATCH: dict[str, _RenderFn] = {
    ".mcp.json": _render_mcp_json_content,
    ".codex/config.toml": _render_codex_config_content,
    ".hermes/config.yaml": _render_hermes_config_content,
}


def render_runtime_config(project: Path, rel: str) -> str:
    """Would-be content for *rel* in ``_RUNTIME_CONFIG_PATHS``.  Never writes.

    Args:
        project: Project root.
        rel: One of ``.mcp.json``, ``.codex/config.toml``, ``.hermes/config.yaml``.

    Raises:
        ValueError: If *rel* is not a known runtime config path.
    """
    renderer = _RENDER_DISPATCH.get(rel)
    if renderer is None:
        msg = f"unknown runtime config rel: {rel!r}"
        raise ValueError(msg)
    return renderer(project)


def apply_runtime_config(
    project: Path,
    rel: str,
    *,
    ignore_tracked: bool = False,
) -> ConfigApplyResult:
    """Guarded write for a runtime config file.

    Guards: main-checkout -> tracked -> render -> unchanged check -> write.

    Args:
        project: Project root.
        rel: One of the ``_RUNTIME_CONFIG_PATHS`` values.
        ignore_tracked: When True, write even if the file is git-tracked.

    Returns:
        Structured result with status and was_tracked flag.

    Raises:
        ValueError: If *rel* is not a known runtime config path.
    """
    if rel not in _RENDER_DISPATCH:
        msg = f"unknown runtime config rel: {rel!r}"
        raise ValueError(msg)

    # Guard 1: main checkout
    if not (project / ".git").is_dir():
        return ConfigApplyResult(status="not-main-checkout")

    # Guard 2: git-tracked
    tracked = _is_git_tracked(project, rel)
    if tracked and not ignore_tracked:
        return ConfigApplyResult(status="git-tracked", was_tracked=True)

    content = render_runtime_config(project, rel)
    config_path = project / rel
    wrote = _write_config_if_changed(config_path, content)

    if wrote:
        return ConfigApplyResult(status="written", was_tracked=tracked)
    return ConfigApplyResult(status="unchanged", was_tracked=tracked)


def ensure_mcp_json(project: Path) -> bool:
    """Write ``.mcp.json`` at *project* when it is a main checkout (RAISE-15848).

    A main checkout has ``.git`` as a directory, unlike a linked worktree where
    ``.git`` is a file pointer (``gitdir:`` prefix).  Uses the same
    ``McpJsonGenerator`` + upsert machinery as ``rai worktree register`` so
    the generated content is identical: absolute path to ``.venv-mcp/bin/
    rai-mcp-pipeline`` and ``--project <absolute-root>`` (RAISE-10767, AC2).

    Called from ``build_open_report`` (``rai session open`` / ``raise_session_open``)
    so that developers get a working ``.mcp.json`` the first time they open a
    session on the root checkout — no manual ``rai worktree register`` needed.

    Returns ``True`` when the file was written or updated; ``False`` when
    *project* is a linked worktree (skipped) or git-tracking guards blocked
    the write.
    """
    if not (project / ".git").is_dir():
        # Linked worktree: .git is a file (gitdir pointer).  Provisioning
        # for linked worktrees is handled by ``rai worktree register``.
        return False
    provisioner = WorktreeProvisioner(project, project)
    return provisioner._write_mcp_json()  # type: ignore[reportPrivateUsage]


def ensure_runtime_config(project: Path, rel: str) -> bool:
    """Write a runtime config (codex/hermes) at *project/rel* when main checkout.

    Symmetric with ``ensure_mcp_json``: dispatches to the existing private
    writers for ``.codex/config.toml`` and ``.hermes/config.yaml``.
    Cleaner never calls privates directly.

    Returns ``True`` when the file was written or updated; ``False`` when
    *project* is a linked worktree or guards blocked the write.
    """
    if not (project / ".git").is_dir():
        return False
    provisioner = WorktreeProvisioner(project, project)
    if rel == ".codex/config.toml":
        return provisioner._write_codex_config()  # type: ignore[reportPrivateUsage]
    if rel == ".hermes/config.yaml":
        return provisioner._write_hermes_config()  # type: ignore[reportPrivateUsage]
    return False
