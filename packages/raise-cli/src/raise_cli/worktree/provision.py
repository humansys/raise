class HermesServerEntry(BaseModel, frozen=True):
    """A single MCP server entry in .hermes/config.yaml."""

    command: str
    args: list[str] = []
    timeout: int = 120
    connect_timeout: int = 60


class HermesConfig(BaseModel):
    """Complete .hermes/config.yaml structure."""

    mcp_servers: dict[str, HermesServerEntry] = {}

    def to_yaml(self) -> str:
        """Serialize to YAML string."""
        data = {
            "mcp_servers": {
                name: {
                    "command": entry.command,
                    "args": entry.args,
                    "timeout": entry.timeout,
                    "connect_timeout": entry.connect_timeout,
                }
                for name, entry in self.mcp_servers.items()
            }
        }
        return "# Auto-generated by rai worktree register --provision\n" + yaml.dump(
            data, default_flow_style=False, sort_keys=False
        )


class ProvisionResult(BaseModel):
    """Result of a worktree provisioning operation."""

